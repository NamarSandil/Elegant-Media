def main():
    t = load_translations()
    outputs = {}
    for page in PAGES:
        path = os.path.join(ROOT, page)
        template = io.open(path, encoding="utf-8").read()
        for lang in LANGS:
            outputs[LANGS[lang]["folder"] + page] = build_page(template, page, lang, t)
    outputs["sitemap.xml"] = sitemap()
    outputs["404.html"] = not_found_page()

    # Everything built without error - only now touch the disk, and only
    # files whose content actually changed.
    changed = []
    for rel, content in outputs.items():
        path = os.path.join(ROOT, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        old = io.open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old != content:
            io.open(path, "w", encoding="utf-8", newline="").write(content)
            changed.append(rel)
    print("built %d files, %d changed%s" % (len(outputs), len(changed),
                                            (": " + ", ".join(changed)) if changed else ""))


if __name__ == "__main__":
    try:
        main()
    except BuildError as err:
        print("BUILD FAILED - nothing was written.\n" + str(err), file=sys.stderr)
        sys.exit(1)
