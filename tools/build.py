# --------------------------------------------------------------- i18n.js

def load_translations():
    """Read i18n.js into {lang: {key: value}}.

    Relies on the file's layout: one `  xx: {` line opens each language, one
    key: 'value' pair (or several) per line, `  },` closes it. Values may be
    single- or double-quoted and use backslash escapes."""
    src = io.open(os.path.join(ROOT, "i18n.js"), encoding="utf-8").read()
    src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)       # drop comments
    pair = re.compile(r"""(\w+)\s*:\s*('(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*")""")
    out, lang = {}, None
    for line in src.split("\n"):
        m = re.match(r"^  (\w+): \{\s*$", line)
        if m:
            lang = m.group(1)
            out[lang] = {}
            continue
        if re.match(r"^  \},?\s*$", line):
            lang = None
            continue
        if lang:
            for key, raw in pair.findall(line):
                out[lang][key] = re.sub(r"\\(.)", r"\1", raw[1:-1])
    missing_langs = [l for l in LANGS if l not in out]
    if missing_langs:
        raise BuildError("i18n.js has no block for: " + ", ".join(missing_langs))
    return out


# ------------------------------------------------------------- filling text

def _matching_close(text, tag, start):
    """Index of the close tag that matches an already-opened <tag>."""
    depth, pos = 1, start
    pat = re.compile(r"<(/?)%s\b" % re.escape(tag), re.I)
    while depth:
        m = pat.search(text, pos)
        if not m:
            raise BuildError("unclosed <%s>" % tag)
        depth += -1 if m.group(1) else 1
        pos = m.end()
    return m.start()


def _set_attr(tag_html, name, value):
    """Set (or replace) one attribute on a start tag."""
    value = html.escape(value, quote=True)
    stripped = re.sub(r'\s%s="[^"]*"' % re.escape(name), "", tag_html)
    return re.sub(r"(\s*/?>)$", ' %s="%s"\\1' % (name, value), stripped, count=1)


def fill_text(page_html, strings, where):
    """Fill every data-i18n* hook from `strings`. Raises on a missing key."""
    missing = set()

    # Inner content. Hooks nested inside another hook are skipped: the outer
    # one's text replaces them anyway (this mirrors what the browser does).
    spans = []
    for m in re.finditer(r'<([a-z0-9]+)(?=[\s>])[^>]*\bdata-i18n="([a-z0-9_]+)"[^>]*>', page_html, re.I):
        spans.append((m.start(), m.end(), _matching_close(page_html, m.group(1), m.end()), m.group(2)))
    outer = [s for s in spans if not any(o[0] < s[0] and s[2] <= o[2] for o in spans if o is not s)]
    for _, inner_start, inner_end, key in sorted(outer, key=lambda s: -s[0]):
        if key not in strings:
            missing.add(key)
            continue
        page_html = page_html[:inner_start] + strings[key] + page_html[inner_end:]

    # Attributes: placeholder, aria-label, alt.
    for hook, attr in (("data-i18n-ph", "placeholder"), ("data-i18n-aria", "aria-label"),
                       ("data-i18n-alt", "alt")):
        def repl(m, attr=attr):
            key = m.group(1)
            if key not in strings:
                missing.add(key)
                return m.group(0)
            return _set_attr(m.group(0), attr, strings[key])
        page_html = re.sub(r'<[a-z0-9]+[^>]*\b%s="([a-z0-9_]+)"[^>]*>' % hook, repl, page_html, flags=re.I)

    if missing:
        raise BuildError("%s: missing text keys %s" % (where, ", ".join(sorted(missing))))
    return page_html


# ------------------------------------------------------------ addresses

def page_path(page):
    return "" if page == "index.html" else page


def absolute_url(page, lang):
    return SITE + LANGS[lang]["folder"] + page_path(page)


def relative_url(page, from_lang, to_lang):
    """Link from `page` in one language to the same page in another."""
    if from_lang == to_lang:
        return page_path(page) or "./"
    up = "../" if LANGS[from_lang]["folder"] else ""
    return (up + LANGS[to_lang]["folder"] + page_path(page)) or "./"


def rebase_assets(page_html):
    """For pages one folder down: point relative links at shared files
    (styles.css, script.js, favicons, assets/...) back up to the root. Links
    between the site's own pages stay as they are - they should stay inside
    the same language."""
    pages = tuple(PAGES)

    def fix(url):
        if re.match(r"^(#|[a-z][a-z0-9+.-]*:|/|\.\./)", url, re.I):
            return url                           # anchor, absolute, already rebased
        if url.split("#")[0] in pages or url in ("", "./"):
            return url
        return "../" + url

    def attr(m):
        return '%s="%s"' % (m.group(1), fix(m.group(2)))

    def srcset(m):
        parts = [p.strip() for p in m.group(1).split(",")]
        fixed = []
        for p in parts:
            bits = p.split(None, 1)
            fixed.append(" ".join([fix(bits[0])] + bits[1:]))
        return 'srcset="%s"' % ", ".join(fixed)

    page_html = re.sub(r'\b(src|href)="([^"]*)"', attr, page_html)
    return re.sub(r'\bsrcset="([^"]*)"', srcset, page_html)


# --------------------------------------------------------- generated parts

def head_block(page, lang, strings, t):
    meta = PAGES[page]
    title, desc = strings["meta_%s_title" % meta], strings["meta_%s_desc" % meta]
    url = absolute_url(page, lang)
    e = lambda s: html.escape(s, quote=True)
    lines = [
        "<!-- Generated by tools/build.py: edit the wording in i18n.js (meta_* keys). -->",
        "<title>%s</title>" % html.escape(title, quote=False),
        '<meta name="description" content="%s" />' % e(desc),
        '<link rel="canonical" href="%s" />' % url,
    ]
    # Google looks for this on the property's own address - the Swedish home.
    if page == "index.html" and lang == DEFAULT and GOOGLE_SITE_VERIFICATION:
        lines.insert(3, '<meta name="google-site-verification" content="%s" />'
                     % e(GOOGLE_SITE_VERIFICATION))
    for other in LANGS:
        lines.append('<link rel="alternate" hreflang="%s" href="%s" />' % (other, absolute_url(page, other)))
    lines.append('<link rel="alternate" hreflang="x-default" href="%s" />' % absolute_url(page, DEFAULT))
    lines += [
        "",
        '<meta property="og:type" content="website" />',
        '<meta property="og:site_name" content="ELEGANTMEDIA" />',
        '<meta property="og:locale" content="%s" />' % strings["_locale"],
    ]
    for other in LANGS:
        if other != lang:
            lines.append('<meta property="og:locale:alternate" content="%s" />' % t[other]["_locale"])
    lines += [
        '<meta property="og:title" content="%s" />' % e(title),
        '<meta property="og:description" content="%s" />' % e(desc),
        '<meta property="og:url" content="%s" />' % url,
        '<meta property="og:image" content="%s" />' % e(OG_IMAGE),
        '<meta property="og:image:width" content="1200" />',
        '<meta property="og:image:height" content="630" />',
        '<meta property="og:image:alt" content="%s" />' % e(strings["meta_og_alt"]),
        '<meta name="twitter:card" content="summary_large_image" />',
        "",
        "<!-- Only this language's two font families are downloaded. -->",
        '<link rel="preconnect" href="https://fonts.googleapis.com" />',
        '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />',
        '<link rel="stylesheet" href="%s" />' % e(LANGS[lang]["fonts"]),
    ]
    if page == "index.html":
        data = dict(BUSINESS, description=strings["meta_home_desc"])
        body = json.dumps(data, ensure_ascii=False, indent=2).replace("</", "<\\/")
        lines += ["", '<script type="application/ld+json">'] + body.split("\n") + ["</script>"]
    return "\n".join(("  " + l) if l else "" for l in lines) + "\n"


def switch_block(page, lang, strings):
    links = []
    for other in SWITCH_ORDER:
        current = other == lang
        links.append('<a class="lang-btn%s" href="%s" hreflang="%s" lang="%s"%s>%s</a>' % (
            " active" if current else "", relative_url(page, lang, other), other, other,
            ' aria-current="page"' if current else "", SWITCH_LABEL[other]))
    pad = "          "
    return ('\n%s<div class="lang-switch" id="langSwitch" role="group" data-i18n-aria="a11y_lang" aria-label="%s">\n'
            % (pad[:-2], html.escape(strings["a11y_lang"], quote=True))
            + "".join("%s%s\n" % (pad, l) for l in links) + pad[:-2] + "</div>\n" + pad[:-2])


def generated_banner(page):
    return ("<!--\n  GENERATED by tools/build.py from ../%s and ../i18n.js - do not edit.\n"
            "  Any change made here is overwritten by the next build.\n-->\n" % page)


# ------------------------------------------------------------------ build

def build_page(template, page, lang, t):
    strings = t[lang]
    where = "%s%s" % (LANGS[lang]["folder"], page)
    if not HEAD_SLOT.search(template) or not SWITCH_SLOT.search(template):
        raise BuildError(page + ": the build:head / build:lang-switch markers are missing")

    # start from empty slots, so rebuilding never nests old output
    out = HEAD_SLOT.sub(r"\1\2", template)
    out = SWITCH_SLOT.sub(r"\1\2", out)
    out = fill_text(out, strings, where)

    sub = bool(LANGS[lang]["folder"])
    root_attr = ' data-root="../"' if sub else ""
    out = re.sub(r"<html[^>]*>", '<html lang="%s" dir="%s"%s>' % (lang, strings["_dir"], root_attr), out, count=1)
    if sub:
        out = rebase_assets(out)
        out = TEMPLATE_BANNER.sub(lambda m: generated_banner(page), out, count=1)

    out = HEAD_SLOT.sub(lambda m: m.group(1) + head_block(page, lang, strings, t) + m.group(2), out)
    out = SWITCH_SLOT.sub(lambda m: m.group(1) + switch_block(page, lang, strings) + m.group(2), out)
    return out


def sitemap():
    rows = ['<?xml version="1.0" encoding="UTF-8"?>',
            "<!-- Generated by tools/build.py. Submit this address in Google Search Console. -->",
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" '
            'xmlns:xhtml="http://www.w3.org/1999/xhtml">']
    for page in PAGES:
        for lang in LANGS:
            rows.append("  <url>")
            rows.append("    <loc>%s</loc>" % absolute_url(page, lang))
            for other in LANGS:
                rows.append('    <xhtml:link rel="alternate" hreflang="%s" href="%s"/>' % (other, absolute_url(page, other)))
            rows.append('    <xhtml:link rel="alternate" hreflang="x-default" href="%s"/>' % absolute_url(page, DEFAULT))
            rows.append("  </url>")
    rows.append("</urlset>")
    return "\n".join(rows) + "\n"


