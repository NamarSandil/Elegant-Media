"""Build the English and Arabic pages from the Swedish templates.

    python tools/build.py

The Swedish pages - index.html, webbdesign.html, integritet.html - are the
templates. Every piece of translatable text in them carries a data-i18n*
attribute naming a key in i18n.js. For each page and each language this:

  1. fills in the text from i18n.js
  2. builds the <head>: title, description, canonical address, the hreflang
     links that tell Google the three versions are one page in three
     languages, social-media preview tags, that language's fonts, and on the
     home page the business listing data
  3. builds the language switcher as links to the same page in the other
     languages
  4. writes Swedish back in place and the others to en/ and ar/

It also writes sitemap.xml and 404.html.

Running it twice gives the same result. If any text key is missing in any
language it stops with an error and writes nothing. Standard library only -
there is nothing to install. GitHub runs this automatically on every push
that changes the text or a template (.github/workflows/build-pages.yml).
"""
